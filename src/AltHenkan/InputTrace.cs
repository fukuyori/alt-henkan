using System.Diagnostics;
using System.Threading.Channels;

namespace AltHenkan;

internal enum InputTraceKind { KeyBegin, KeyEnd, MouseBegin, MouseEnd, SendBegin, SendItem, SendEnd, State, Boundary, Settings, Status, Fallback }
internal enum InputTraceKey { Other, LeftControl, RightControl, LeftAlt, RightAlt, Shift, Windows, CapsLock }
internal enum InputTraceVerdict { None, Forwarded, Suppressed, Exception }
internal enum InputTraceReason
{
    None, OwnInput, Inactive, ControlRepeat, ControlNativeNotDeferrable, ControlNativeOtherInput, ControlDeferred, ControlUnknownUp,
    ControlPassedUp, ControlSentUp, ControlTapOrConsumed, AltRepeatNative, AltRepeatHidden,
    AltNative, AltDeferred, AltUnknownUp, AltPassedUp, AltSentUp, AltConsumed, AltTap,
    CapsLock, Emacs, ImeWidth, PromoteControl, PromoteAlt, ConsumeControl, Navigation,
    ImeTap, ControlSend, AltSend, CapsReset, Settings, ResetBegin, ResetEnd,
    Disabled, Suspend, SessionLock, Renewal, Shutdown, Registered, RecoveredAlt, Maintenance,
    Startup, BeforeReset, CallbackFailed, Unregistered, ModifierReleaseResidual, ControlRepeatNative, RecoveredControl
}

// No ordinary key code, scan code, text, window title, or clipboard is stored here.
internal readonly record struct InputTraceSnapshot(uint State, byte AsyncRaw, int Captured, int NonAltKeys);
internal readonly record struct InputTraceEvent
{
    public InputTraceKind Kind { get; init; }
    public InputTraceReason Reason { get; init; }
    public long Observation { get; init; }
    public long Parent { get; init; }
    public long Batch { get; init; }
    public long ParentBatch { get; init; }
    public uint Token { get; init; }
    public int Index { get; init; }
    public int Depth { get; init; }
    public InputTraceKey Key { get; init; }
    public bool Up { get; init; }
    public uint Flags { get; init; }
    public bool Own { get; init; }
    public uint EventTime { get; init; }
    public InputTraceSnapshot Snapshot { get; init; }
    public InputTraceVerdict Verdict { get; init; }
    public long Result { get; init; }
    public long ElapsedTicks { get; init; }
    public int Requested { get; init; }
    public uint Sent { get; init; }
    public int Error { get; init; }
    // Scan codes are populated ONLY for inputs generated by this application.
    public ushort SentScan { get; init; }
    public ushort SentVirtualKey { get; init; }
    public nint Foreground { get; init; }
    public uint ForegroundProcess { get; init; }
    public uint ForegroundThread { get; init; }
    public long KeyboardCallbacks { get; init; }
    public long MouseCallbacks { get; init; }
    public uint SettingsBits { get; init; }
    public int LongPressMilliseconds { get; init; }
    public uint Shortcuts { get; init; }
}

internal static class InputTrace
{
    private static InputTraceWriter? _writer;
    private static long _recordFailures;
    public static Guid Session { get; private set; }
    public static long RecordFailures => Interlocked.Read(ref _recordFailures);
    public static void RecordFailure() => Interlocked.Increment(ref _recordFailures);
    public static bool Enabled => Volatile.Read(ref _writer)?.Accepting == true;
    public static long Dropped => Volatile.Read(ref _writer)?.Dropped ?? 0;
    public static Exception? LastError => Volatile.Read(ref _writer)?.LastError;
    public static void Initialize(string path, Guid session)
    {
        Shutdown();
        Session = session;
        Interlocked.Exchange(ref _recordFailures, 0);
        _writer = new InputTraceWriter(() => new RotatingDiagnosticWriter(path,
            4 * 1024 * 1024, 4, flushEveryLine: false), session);
    }
    public static long Record(in InputTraceEvent entry)
    {
        var writer = Volatile.Read(ref _writer);
        if (writer is null) return 0;
        writer.TryWrite(entry, out var sequence);
        return sequence;
    }
    public static void Shutdown() => Interlocked.Exchange(ref _writer, null)?.Dispose();

    public static InputTraceKey Classify(uint key, uint flags) => key switch
    {
        NativeMethods.VkLControl => InputTraceKey.LeftControl,
        NativeMethods.VkRControl => InputTraceKey.RightControl,
        NativeMethods.VkControl => (flags & NativeMethods.LlkhfExtended) != 0 ? InputTraceKey.RightControl : InputTraceKey.LeftControl,
        NativeMethods.VkLMenu => InputTraceKey.LeftAlt,
        NativeMethods.VkRMenu => InputTraceKey.RightAlt,
        NativeMethods.VkMenu => (flags & NativeMethods.LlkhfExtended) != 0 ? InputTraceKey.RightAlt : InputTraceKey.LeftAlt,
        NativeMethods.VkShift or NativeMethods.VkLShift or NativeMethods.VkRShift => InputTraceKey.Shift,
        NativeMethods.VkLWin or NativeMethods.VkRWin => InputTraceKey.Windows,
        NativeMethods.VkCapsLock => InputTraceKey.CapsLock,
        _ => InputTraceKey.Other
    };
}

// Bounded, nonblocking producers. All formatting, file access, and periodic flushing
// run on the consumer, independently of the input thread's maintenance timer.
internal sealed class InputTraceWriter : IDisposable
{
    private readonly record struct Entry(long Seq, long Qpc, InputTraceEvent Value);
    private readonly Channel<Entry> _queue;
    private readonly Task _worker;
    private readonly TaskCompletionSource _stop = new(TaskCreationOptions.RunContinuationsAsynchronously);
    private readonly Action<string> _report;
    private long _sequence;
    private long _dropped;
    private Exception? _lastError;
    private int _accepting = 1;
    public bool Accepting => Volatile.Read(ref _accepting) != 0;
    public long Dropped => Interlocked.Read(ref _dropped);
    public Exception? LastError => Volatile.Read(ref _lastError);
    public Task Completion => _worker;

    public InputTraceWriter(Func<TextWriter> createWriter, Guid session, int capacity = 8192,
        Action<string>? report = null, TimeSpan? retryDelay = null)
    {
        _report = report ?? DiagnosticLog.Write;
        _queue = Channel.CreateBounded<Entry>(new BoundedChannelOptions(capacity)
        { SingleReader = true, SingleWriter = false, FullMode = BoundedChannelFullMode.Wait });
        var utc = DateTimeOffset.UtcNow;
        var qpc = Stopwatch.GetTimestamp();
        var header = $"Input trace session={session:N} utc={utc:O} qpc={qpc} frequency={Stopwatch.Frequency} version={typeof(InputTrace).Assembly.GetName().Version} schema=2";
        _worker = Task.Run(async () =>
        {
            TextWriter? writer = null;
            long outageStart = 0;
            long reportedDrops = 0;
            try
            {
                while (true)
                {
                    // A dequeued entry may fail to reach disk. Count it, but do not replay:
                    // the write may have completed partially before throwing.
                    var writingEntry = false;
                    try
                    {
                        if (writer is null)
                        {
                            writer = createWriter();
                            if (writer is RotatingDiagnosticWriter rotating) rotating.SetHeader(header);
                            else await writer.WriteLineAsync(header);
                            if (outageStart != 0)
                            {
                                var recoveredAt = Stopwatch.GetTimestamp();
                                await writer.WriteLineAsync($"Trace outage: fromQpc={outageStart} toQpc={recoveredAt} observationPaused=True unflushedMayBeLost=True droppedTotal={Dropped}");
                                await writer.FlushAsync();
                                Report($"Input trace recovered: session={session:N}, fromQpc={outageStart}, toQpc={recoveredAt}, droppedTotal={Dropped}.");
                                outageStart = 0;
                            }
                            Volatile.Write(ref _lastError, null);
                            if (!_stop.Task.IsCompleted) Volatile.Write(ref _accepting, 1);
                        }
                        // Bound each drain so continuous input cannot postpone flushing indefinitely.
                        for (var i = 0; i < 8192 && _queue.Reader.TryRead(out var entry); i++)
                        {
                            writingEntry = true;
                            await writer.WriteLineAsync(Format(entry.Seq, entry.Qpc, entry.Value));
                            writingEntry = false;
                        }
                        var drops = Dropped;
                        if (drops != reportedDrops)
                        {
                            await writer.WriteLineAsync($"Trace gap: droppedTotal={drops}, latestSeq={Interlocked.Read(ref _sequence)}");
                            reportedDrops = drops;
                        }
                        await writer.FlushAsync();
                        if (_queue.Reader.Completion.IsCompleted)
                        {
                            await writer.WriteLineAsync($"Input trace ended: latestSeq={Interlocked.Read(ref _sequence)}, droppedTotal={Dropped}");
                            await writer.FlushAsync();
                            break;
                        }
                        await Task.WhenAny(Task.Delay(250), _stop.Task);
                    }
                    catch (Exception exception)
                    {
                        Volatile.Write(ref _accepting, 0);
                        Volatile.Write(ref _lastError, exception);
                        if (writingEntry) Interlocked.Increment(ref _dropped);
                        if (outageStart == 0)
                        {
                            outageStart = Stopwatch.GetTimestamp();
                            Report($"Input trace write failed: session={session:N}, qpc={outageStart}, latestSeq={Interlocked.Read(ref _sequence)}, unflushedMayBeLost=True. Retrying; observations paused. {exception}");
                        }
                        try { writer?.Dispose(); } catch { /* Preserve the first write failure. */ }
                        writer = null;
                        if (_stop.Task.IsCompleted) break;
                        await Task.WhenAny(Task.Delay(retryDelay ?? TimeSpan.FromSeconds(1)), _stop.Task);
                        if (_stop.Task.IsCompleted) break;
                    }
                }
            }
            finally
            {
                Volatile.Write(ref _accepting, 0);
                // At shutdown during an outage, pending entries cannot be saved.
                long abandoned = 0;
                while (_queue.Reader.TryRead(out _)) abandoned++;
                if (abandoned != 0)
                {
                    Interlocked.Add(ref _dropped, abandoned);
                    Report($"Input trace shutdown: abandoned={abandoned}, droppedTotal={Dropped}.");
                }
                try { writer?.Dispose(); }
                catch (Exception exception)
                {
                    Volatile.Write(ref _lastError, exception);
                    Report($"Input trace close failed; unflushedMayBeLost=True. {exception}");
                }
            }
        });
    }

    private void Report(string message)
    {
        try { _report(message); } catch { /* Reporting must not terminate the consumer. */ }
    }

    public bool TryWrite(in InputTraceEvent value) => TryWrite(value, out _);
    public bool TryWrite(in InputTraceEvent value, out long sequence)
    {
        sequence = Interlocked.Increment(ref _sequence);
        var entry = new Entry(sequence, Stopwatch.GetTimestamp(), value);
        if (Accepting && _queue.Writer.TryWrite(entry)) return true;
        Interlocked.Increment(ref _dropped);
        return false;
    }

    internal static string Format(long seq, long qpc, in InputTraceEvent e)
    {
        var text = $"seq={seq} qpc={qpc} kind={e.Kind} reason={e.Reason} obs={e.Observation} parent={e.Parent} batch={e.Batch} index={e.Index} depth={e.Depth}";
        // A SendItem describes the plan, not another state observation.
        if (e.Kind != InputTraceKind.SendItem)
            text += $" state=0x{e.Snapshot.State:X} asyncRaw=0x{e.Snapshot.AsyncRaw:X} captured={e.Snapshot.Captured} nonAltKeys={e.Snapshot.NonAltKeys}";
        if (e.Kind is InputTraceKind.KeyBegin or InputTraceKind.KeyEnd or InputTraceKind.MouseBegin or InputTraceKind.MouseEnd)
            text += $" key={e.Key} up={e.Up} flags=0x{e.Flags:X} own={e.Own} token={e.Token} eventTime={e.EventTime} foreground=0x{e.Foreground:X} pid={e.ForegroundProcess} tid={e.ForegroundThread}";
        if (e.Kind is InputTraceKind.KeyEnd or InputTraceKind.MouseEnd or InputTraceKind.Fallback)
            text += $" verdict={e.Verdict} result={e.Result} elapsedTicks={e.ElapsedTicks}";
        if (e.Kind is InputTraceKind.SendBegin or InputTraceKind.SendEnd)
            text += $" parentBatch={e.ParentBatch} requested={e.Requested}";
        if (e.Kind == InputTraceKind.SendEnd)
            text += $" sent={e.Sent} error={e.Error} elapsedTicks={e.ElapsedTicks}";
        if (e.Kind == InputTraceKind.SendItem)
            text += $" token={e.Token} sentScan=0x{e.SentScan:X} sentVk=0x{e.SentVirtualKey:X} flags=0x{e.Flags:X} up={e.Up} own={e.Own}";
        if (e.Kind == InputTraceKind.Status)
            text += $" keyboardCallbacks={e.KeyboardCallbacks} mouseCallbacks={e.MouseCallbacks}";
        if (e.Kind == InputTraceKind.Settings)
            text += $" settings=0x{e.SettingsBits:X} longPressMs={e.LongPressMilliseconds} shortcuts=0x{e.Shortcuts:X}";
        if (e.Reason == InputTraceReason.ModifierReleaseResidual)
            text += $" key={e.Key} residual=0x{e.Index:X} up={e.Up} flags=0x{e.Flags:X} eventTime={e.EventTime}";
        if (e.Reason == InputTraceReason.RecoveredControl)
            text += $" key={e.Key}";
        return text;
    }

    public void Complete()
    {
        Volatile.Write(ref _accepting, 0);
        _queue.Writer.TryComplete();
        _stop.TrySetResult();
    }
    public bool Stop(TimeSpan timeout)
    {
        Complete();
        if (_worker.Wait(timeout)) return true;
        Report($"Input trace drain timed out: latestSeq={Interlocked.Read(ref _sequence)}, droppedTotal={Dropped}; unsaved entries may remain.");
        return false;
    }
    public void Dispose() => Stop(TimeSpan.FromSeconds(2));
}
